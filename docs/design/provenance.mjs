/* =============================================================================
 * UsArr — the provenance check: prototype.html is in step with its sources.
 *
 *   node docs/design/provenance.mjs          # standalone, and `make provenance`
 *
 * It is ALSO section 1e of docs/design/check.mjs, which imports it and reports
 * through its own counters. It lives here rather than there because check.mjs
 * cannot be entered without a browser — a top-level `await loadChromium()` sits
 * above where 1e used to be — and this check touches no browser, no page and no
 * network. Splitting it out is what let it into `make check`.
 *
 * WHERE IT RUNS, and it is two places on purpose:
 *
 *   · `make check-offline`, FIRST, ahead of fmt-check. It is the cheapest step
 *     in the gate by three orders of magnitude (~70 ms against ~4m10s), so a
 *     stale tree fails before `pnpm install` rather than after it. Its
 *     prerequisites are already the gate's: node is a HARD prerequisite of
 *     `make check` today through web-deps, which fmt-check, lint-web, test-web
 *     and test-go all declare. It adds no new one — node:crypto and node:fs are
 *     stdlib, it opens no socket, and it needs no Chromium.
 *   · `make design`, through check.mjs, where every rendered check downstream
 *     of it opens prototype.html and would otherwise measure a stale artifact.
 *
 * THE HOLE THIS CLOSES. Every rendered check in check.mjs drives
 * prototype.html, and prototype.html is GENERATED by build_prototype.py from
 * the eight mockup files plus the script's own template text. Nothing verified
 * the two were in step, so the rendered half of that gate was blind to edits in
 * the files humans actually edit. Measured before it landed, on origin/main at
 * 9ba240b: a §13 banned word injected into a static <h2> of index.html left
 * `make design` at exit 0, "all design checks pass", with the user-visible
 * string count unchanged at 6932 — while the same word in prototype.html failed
 * §13 copy with 8 violations. The gate was guarding the artifact and ignoring
 * the source.
 *
 * WHY A DIGEST STAMP AND NOT REGENERATE-AND-COMPARE. Regenerating here would be
 * the most direct proof, and it would put a python3 run on every `make check`
 * on every machine, forever, to catch a class of drift that most commits cannot
 * produce at all. Declaring python3 somewhere else in the Makefile does not
 * change that price; it only moves where it is written down. So the proof is
 * taken at GENERATION time, where python3 is already running, and only a
 * comparison is left here. node:crypto is stdlib, so the comparison adds
 * nothing. See "WHAT IT DOES NOT PROVE", hole 3, for what that trade costs.
 *
 * WHY THE STAMP LIVES INSIDE prototype.html AND NOT IN A MANIFEST FILE. The
 * failure mode of any recorded pin is someone bumping it alongside the sources
 * without regenerating, which quietly converts the check into "somebody said
 * so". A manifest sitting beside the sources invites exactly that — it reads as
 * a file that wants updating. The digests instead live inside the generated
 * artifact, under its own do-not-edit-by-hand banner, and build_prototype.py
 * emits them as a byproduct of the reads it already performs rather than from a
 * list kept in step by hand. Editing a source therefore moves the recomputed
 * digest away from a stamp that only a regenerate rewrites, and there is no
 * second file whose update looks like the fix.
 *
 * ONE FORMAT, TWO IMPLEMENTATIONS, AND THAT IS THE CEILING. build_prototype.py
 * writes the stamp; this file reads it. Nothing else may parse it. A third
 * reader — a shell pipeline, a test fixture, a second script — is how a format
 * acquires a dialect, and a dialect in a provenance stamp is a green over an
 * artifact nobody compared.
 *
 * -----------------------------------------------------------------------------
 * WHAT IT DOES NOT PROVE, stated so nobody reads more into a green than is
 * there. THIS IS A CONVENTION-ENFORCED PIN, NOT A PROOF. Three holes, all of
 * them open, all of them disclosed on purpose — an undisclosed hole in a
 * guard's own self-description is the defect this project keeps finding, and a
 * guard that oversells itself is worse than no guard, because it is believed.
 *
 *   1. IT ASSERTS THE WORKING TREE IS IN STEP, NOT THAT THIS COMMIT IS.
 *      Everything below reads files from disk. A commit is a different object,
 *      and the two diverge in at least two ordinary ways, neither of which
 *      needs anybody to be careless:
 *
 *        · you regenerate to unblock yourself and leave the new prototype.html
 *          unstaged — the tree is now in step and the commit is not;
 *        · you stage part of what you changed — `git commit -p`, or a `git add`
 *          naming one file of the pair — so the commit carries the source edit
 *          without the regenerate, or the regenerate without the source edit.
 *
 *      In both cases this check is green and the commit is stale. `make design`
 *      has always made the same disk-only claim about every rendered check it
 *      runs; this is not a new weakness, it is the same one written down.
 *
 *   2. IT CANNOT SEE A HAND-EDITED prototype.html BODY. This compares INPUTS
 *      against a stamp. It does not re-derive the output, so a prototype.html
 *      whose markup was edited while every input stood still passes here. That
 *      one is covered, and deliberately covered elsewhere: every rendered check
 *      in check.mjs opens prototype.html directly, so a hand-edit surfaces as
 *      whichever defect it introduced. The two halves are complementary, which
 *      is why this check was added beside them and replaces none.
 *
 *   3. IT CANNOT SEE A HAND-EDITED STAMP, AND NOTHING ELSE COVERS THAT ONE.
 *      Edit a source, then edit its digest line in the BUILD STAMP banner to
 *      match, and this check is green while every rendered check downstream
 *      goes on measuring the old artifact. That is not a theory about the code:
 *      it was performed. `make design` exited 0 with zero failures over a
 *      prototype.html that did not contain the edit, and the rendered walk
 *      measured the stale file throughout. Note the asymmetry, because it is
 *      counter-intuitive — DELETING a stamp line fails cleanly on the floor of
 *      nine, while REWRITING one does not fail at all.
 *
 *      It is disclosed rather than closed. Closing it means
 *      regenerate-and-compare, and that is ruled out above on cost: it charges
 *      every commit on every machine, forever, for a class of drift that most
 *      commits cannot cause. The hole also requires someone to deliberately
 *      rewrite a digest to match a file they just edited, which is a bad actor,
 *      and the danger this check is actually built against is not one. It is an
 *      ordinary edit followed by an ordinary forgetting — and, one step worse,
 *      a reader in a hurry who is shown two hashes and makes them match the
 *      wrong way. That reader is why the failure message below prints no
 *      digests at all.
 *
 * THE RESIDUE, NAMED RATHER THAN PAPERED OVER: every commit that stages a
 * stamped input separately from prototype.html is outside this check. Nothing
 * in this repo can see that, and nothing here pretends to.
 *
 * AND NOT A PRE-COMMIT HOOK. It is the obvious next proposal, so it is refused
 * here in writing rather than re-argued every six months. Hooks live in
 * .git/hooks, which git does not version: a hook is ABSENT BY DEFAULT on every
 * fresh clone, and its absence is invisible — nothing anywhere reports a guard
 * that was never installed, so the failure mode is a repo that believes it is
 * protected. `core.hooksPath` at a versioned directory does not fix that; it
 * only moves the per-clone opt-in from copying a file to running a config
 * command, and an opt-in nobody performed is still off. Worse, an agent driving
 * git through plumbing — `commit-tree`, `update-ref`, or plain `--no-verify` —
 * never fires a hook at all, and that is precisely the caller this project
 * actually has. A guard that silently does not run is worse than a disclosed
 * hole, because it reads as coverage.
 * ========================================================================== */

import { readFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { basename, dirname, join, relative, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));

/* The one command that makes a red here green. Named once, printed everywhere,
   so the remedy in the message and the remedy in the Makefile cannot drift. */
export const REGEN = 'make prototype';

/* The mockup-directory sources this repo's design gate scans. It is defined
   HERE and imported by check.mjs rather than the other way round, because the
   cross-check further down asks "is every scanned source named by a stamp
   entry?" and a second derivation of "scanned source" would answer a different
   question than the one check.mjs asks. One list, two readers. */
export function mockupSources(mockups) {
  return [
    join(mockups, 'usarr.css'),
    join(mockups, 'fonts.css'),
    join(mockups, 'usarr.js'),
    ...readdirSync(mockups)
      .filter((f) => f.endsWith('.html') && f !== 'prototype.html')
      .sort()
      .map((f) => join(mockups, f)),
  ];
}

/* Nine inputs today — five screens, fonts.css, usarr.css, usarr.js, and
   build_prototype.py, whose own bytes count because the doctype, <head>,
   <title> and banner are template text living there.

   The floor is on the CORPUS, not on the hit count. A ban-shaped check wants
   zero hits, so a zero here is ambiguous: it is also what a renamed marker or a
   changed stamp format produces, and that would report a clean pass having
   compared nothing at all. */
const STAMP_FLOOR = 9;

/* ---------------------------------------------------------------------------
 * Which of the two failures is this?
 *
 * "You edited a source and did not regenerate" and "somebody else's commit
 * arrived with the drift already in it" want OPPOSITE advice about what to
 * commit, and one message covering both is one message that gives half its
 * readers the wrong instruction. git already knows: a drifted source that is
 * dirty in the working tree or the index is yours; one that is clean at HEAD
 * came with the tree.
 *
 * Only ever consulted on the failure path, so the green path stays pure stdlib
 * with no subprocess. Returns null when git cannot answer at all — a tarball, a
 * machine with no git — and the message then covers both cases rather than
 * guessing one.
 * ------------------------------------------------------------------------- */
function dirtyPaths(root, paths) {
  if (!paths.length) return null;
  try {
    const out = execFileSync('git', ['status', '--porcelain', '--', ...paths], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    });
    const dirty = new Set();
    for (const line of out.split('\n')) {
      if (!line.trim()) continue;
      /* "XY path" and, for a rename, "XY old -> new". The new name is the one
         on disk, so it is the one that answers "did you touch this file". */
      const p = line.slice(3).split(' -> ').pop().replace(/^"|"$/g, '');
      dirty.add(p);
    }
    return dirty;
  } catch {
    return null;
  }
}

/* The paragraph that must not be misread. It is printed on every failure that a
   regenerate fixes, and it is the reason no digest appears anywhere above it. */
const NEVER_EDIT_THE_STAMP = [
  'THE FIX IS NEVER TO EDIT THE STAMP. The digests in prototype.html\'s BUILD STAMP banner',
  'are not two numbers to be reconciled — they are the record of what was actually built.',
  'Hand-editing one to match a source turns this check green over an artifact that still',
  'has the OLD bytes inside it, and every rendered check in `make design` then goes on',
  'measuring that old copy with nothing left to notice. Regenerate. There is no second way,',
  'and this check cannot tell the difference, which is why it is spelled out here instead.',
];

/* =============================================================================
 * The check itself.
 *
 * `report` carries the caller's reporting: check.mjs passes its own counting
 * `fail` so a finding here lands in that file's exit code; the standalone entry
 * point at the bottom passes an equivalent. Printing is done here so the text
 * of the failure exists once.
 * ========================================================================== */
export function checkProvenance({ mockups, root, fail, ok, note }) {
  const rel = (p) => relative(root, p);
  const PROTO = join(mockups, 'prototype.html');
  const raw = readFileSync(PROTO, 'utf8');

  const m = raw.match(/BUILD STAMP\b([\s\S]*?)END BUILD STAMP/);
  if (!m) {
    fail(`provenance: ${rel(PROTO)} carries no BUILD STAMP banner, so nothing here can tell ` +
      `whether it is in step with its sources. Either it was generated by a build_prototype.py ` +
      `that no longer writes one, or the banner was deleted by hand. Regenerate: ${REGEN}`);
    return false;
  }

  const entries = [...m[1].matchAll(/^\s*(\S+)\s+sha256:([0-9a-f]{64})\s*$/gm)]
    .map((e) => ({ name: e[1], want: e[2] }));

  if (entries.length < STAMP_FLOOR) {
    fail(`provenance: the BUILD STAMP in ${rel(PROTO)} names only ${entries.length} input ` +
      `digest(s), below the floor of ${STAMP_FLOOR}. A stamp with lines missing is not a stamp ` +
      `that passed — whatever it no longer names sits outside this check entirely, and a green ` +
      `here would be a green over an unmeasured file. Either build_prototype.py stopped reading ` +
      `an input, or the banner was hand-edited. Regenerate with \`${REGEN}\`; if the count is ` +
      `still short afterwards, the builder is what changed and the stamp is telling the truth.`);
    return false;
  }

  const drifted = [];
  for (const { name, want } of entries) {
    let got;
    try {
      got = createHash('sha256').update(readFileSync(join(mockups, name))).digest('hex');
    } catch {
      drifted.push({ name, missing: true });
      continue;
    }
    /* The digests are compared and then DISCARDED — deliberately, and this is
       the one line in the file that would be easiest to "improve" wrongly. The
       previous message printed the on-disk digest beside the stamped one, which
       reads as a pair to be reconciled, and the repair it suggests to a reader
       under time pressure is to make them match. That repair is the forgery in
       hole 3: it produces a green gate over a stale artifact. A file name and
       the word "regenerate" are the whole of what a reader can act on. */
    if (got !== want) drifted.push({ name, missing: false });
  }

  /* The other direction, which the digest loop above cannot see: a mockup
     source this gate already scans that the stamp does not name at all. That is
     a builder which stopped reading a file, not a stale generate, and it would
     otherwise leave that file permanently outside the freshness check. */
  const stamped = new Set(entries.map((e) => e.name));
  const unstamped = mockupSources(mockups)
    .filter((p) => !stamped.has(basename(p)))
    .map((p) => rel(p));

  if (drifted.length) {
    const paths = drifted.map((d) => join(mockups, d.name));
    const dirty = dirtyPaths(root, paths.map((p) => rel(p)));
    const mine = dirty === null ? null : drifted.some((d) => dirty.has(rel(join(mockups, d.name))));

    fail(`provenance: ${rel(PROTO)} is STALE — ${drifted.length} of its ${entries.length} inputs ` +
      `${drifted.length === 1 ? 'has' : 'have'} changed since it was generated. ` +
      `Every rendered check in \`make design\` opens ` +
      `${rel(PROTO)}, so until it is regenerated they are measuring the OLD copy and every edit ` +
      `to the file(s) below is unguarded. This is not a finding about what is IN those files — ` +
      `it is a finding that they were never built in.`);
    note('');
    for (const d of drifted) {
      note(`  ${rel(join(mockups, d.name))}` +
        (d.missing ? '  — stamped as an input but not readable in the tree'
          : dirty === null ? '  — changed since the last generate'
            : dirty.has(rel(join(mockups, d.name))) ? '  — changed by you, and not built in'
              : '  — clean at HEAD, and not built in'));
    }
    note('');

    if (mine === true) {
      note('YOU CHANGED THIS. At least one file above is modified in your working tree or');
      note('index, so the edit is yours and so is the regenerate. Run:');
      note('');
      note(`    ${REGEN}`);
      note('');
      note('Then commit the regenerated file IN THE SAME COMMIT as the source edit above:');
      note('');
      note(`    ${rel(PROTO)}`);
      note('');
      note('A source edit that ships without its regenerate is exactly the drift this check');
      note('exists to catch, and it lands on whoever pulls next as a failure they did not');
      note('cause and are told, correctly, not to commit the fix for.');
    } else if (mine === false) {
      note('YOU DID NOT DO THIS. Every file above is clean at HEAD, so the drift arrived with');
      note('somebody else\'s commit or a merge — it was already here when you started, and it is');
      note('blocking you rather than accusing you. Regenerate to unblock yourself:');
      note('');
      note(`    ${REGEN}`);
      note('');
      note('Then do NOT let the regenerated file ride along in your commit:');
      note('');
      note(`    ${rel(PROTO)}`);
      note('');
      note('It is not your change. Stage your own files BY NAME — `git add <path>` — and never');
      note('`git add -u`, `git add -A` or `git add .`, all three of which sweep it in without');
      note('asking. This repo has already shipped exactly that sweep once, on an unrelated file,');
      note('and this message is the only place that warning will be read. Leave the regenerate');
      note('unstaged, or put it back after you commit with:');
      note('');
      note(`    git checkout -- ${rel(PROTO)}`);
      note('');
      note('and let the lane that owns the source edit ship its own regenerate.');
    } else {
      note('git could not be asked which of these two cases this is, so both are stated.');
      note(`Either way the remedy is the same command — \`${REGEN}\` — and only the commit`);
      note('differs. IF THE EDIT IS YOURS: commit the regenerated prototype.html in the same');
      note('commit as the source edit. IF IT IS NOT: regenerate to unblock yourself, then keep');
      note('the result OUT of your commit — stage your own files by name, never `git add -u`,');
      note('`git add -A` or `git add .`, because the regenerate is not your change.');
    }
    note('');
    NEVER_EDIT_THE_STAMP.forEach((l) => note(l));

    if (unstamped.length) {
      note('');
      note(`Separately, ${unstamped.length} source(s) this gate scans are named by no stamp entry:`);
      unstamped.forEach((u) => note(`  ${u}`));
      note('That is build_prototype.py having stopped reading a file, not a stale generate, and a');
      note('regenerate will not fix it — the builder is what needs the change.');
    }
    return false;
  }

  if (unstamped.length) {
    fail(`provenance: ${unstamped.length} mockup source(s) this gate scans are named by no BUILD ` +
      `STAMP entry, so they sit permanently outside the freshness check and could drift forever ` +
      `without turning anything red. This is not a stale generate and \`${REGEN}\` will not fix ` +
      `it: build_prototype.py has stopped reading a file it used to read, and the builder is what ` +
      `needs the change.`);
    note('');
    unstamped.forEach((u) => note(`  ${u}  — scanned by this gate but named by no stamp entry`));
    return false;
  }

  ok(`provenance: ${rel(PROTO)} is in step with all ${entries.length} of its inputs ` +
    `[sha256 re-hashed from disk and compared against the stamp it was generated with, ` +
    `floor ${STAMP_FLOOR}] — a convention-enforced pin, not a proof; see the header of ` +
    `${rel(join(HERE, 'provenance.mjs'))} for the three things it does not cover`);
  return true;
}

/* =============================================================================
 * Standalone entry point — `make provenance`, and the first step of
 * `make check-offline`.
 *
 * Exit 1 on any failure, 0 otherwise. That is THIS SCRIPT's exit code; a `make`
 * target whose recipe fails exits 2, so the two numbers are not the same number
 * and neither one should be quoted for the other.
 * ========================================================================== */
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  let failures = 0;
  const failed = checkProvenance({
    mockups: join(HERE, 'mockups'),
    root: resolve(join(HERE, '..', '..')),
    fail: (msg) => { failures++; console.log('FAIL  ' + msg); },
    ok: (msg) => console.log('ok    ' + msg),
    note: (msg) => console.log(msg ? '      ' + msg : ''),
  });
  void failed;
  process.exit(failures ? 1 : 0);
}
